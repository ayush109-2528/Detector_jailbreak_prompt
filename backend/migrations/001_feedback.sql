-- Run once in Supabase SQL Editor before starting the hosted backend.
-- Keep research outside the schemas exposed through the Supabase Data API.
-- Before running on a shared project, confirm these named objects belong to this app.
-- Do not change grants on the entire schema or unrelated existing tables.
BEGIN;
CREATE SCHEMA IF NOT EXISTS research;
CREATE TABLE IF NOT EXISTS research.analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prompt_key TEXT NOT NULL,
    created_at TEXT NOT NULL,
    result_json TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS analyses_prompt_key_id ON research.analyses (prompt_key, id);
CREATE TABLE IF NOT EXISTS research.reviews (
    prompt_key TEXT PRIMARY KEY,
    label INTEGER NOT NULL CHECK (label IN (0, 1)),
    category TEXT NOT NULL,
    reviewed_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS research.review_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prompt_key TEXT NOT NULL,
    label INTEGER NOT NULL CHECK (label IN (0, 1)),
    category TEXT NOT NULL,
    reviewed_at TEXT NOT NULL
);
REVOKE ALL ON TABLE research.analyses, research.reviews, research.review_audit
    FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE research.analyses_id_seq, research.review_audit_id_seq
    FROM PUBLIC, anon, authenticated;
COMMIT;
